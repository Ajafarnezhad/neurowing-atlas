const DIFFICULTY_KEY = {'آسان':'task.filter_easy','متوسط':'task.filter_medium','سخت':'task.filter_hard'};

let current = (function(){
  try { return localStorage.getItem('nw_lang') || document.documentElement.getAttribute('lang') || 'fa'; }
  catch(e){ return 'fa'; }
})();

function t(key){
  const d = DICT[current] || DICT.fa;
  return (key in d) ? d[key] : (DICT.fa[key] || key);
}

function applyDom(){
  document.documentElement.setAttribute('lang', current);
  document.documentElement.setAttribute('dir', current === 'en' ? 'ltr' : 'rtl');
  document.querySelectorAll('[data-i18n]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'))); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.setAttribute('title', t(el.getAttribute('data-i18n-title'))); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
  const langBtn = document.getElementById('langBtn');
  if (langBtn) langBtn.textContent = t('header.lang_btn');
  document.dispatchEvent(new CustomEvent('nw:langchange', { detail: { lang: current } }));
}

function setLang(lang){
  current = (lang === 'en') ? 'en' : 'fa';
  try { localStorage.setItem('nw_lang', current); } catch(e){}
  applyDom();
}

function toggle(){ setLang(current === 'en' ? 'fa' : 'en'); }

function taskText(task){
  if (current === 'en' && task && TASKS_EN[task.id]) return { title: TASKS_EN[task.id].title, goal: TASKS_EN[task.id].goal };
  return { title: task?.title, goal: task?.goal };
}
function difficultyText(d){ return t(DIFFICULTY_KEY[d] || 'task.filter_hard'); }

root.I18N = { t, setLang, toggle, taskText, difficulty: difficultyText, refresh: applyDom, get lang(){ return current; } };
document.addEventListener('DOMContentLoaded', () => {
  applyDom();
  const langBtn = document.getElementById('langBtn');
  if (langBtn) langBtn.addEventListener('click', toggle);
});
